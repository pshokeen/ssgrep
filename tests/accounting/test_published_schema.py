def encoded(document):
    return (json.dumps(document, ensure_ascii=False, indent=2) + "\n").encode()


@pytest.mark.parametrize(
    "kind,raw",
    [("history", GENUINE_HISTORY), ("receipt", GENUINE_RECEIPT), ("receipt", encoded(receipt()))],
)
def test_supported_original_publication_preserves_exact_bytes_and_sha(kind, raw):
    if kind == "history":
        assert hashlib.sha256(raw).hexdigest() == GENUINE_SHA
    reference = _envelope(PROFILE, raw, kind, 3, "2026-10-14T12:00:00Z")
    archived = store.read_blob(PROFILE, reference)
    assert archived is not None
    assert archived["original_utf8"].encode() == raw
    assert archived["sha256"] == hashlib.sha256(raw).hexdigest()
    assert (
        archived["source_generation"] == 3
        and archived["original_collected_at"] == "2026-10-14T12:00:00Z"
    )


