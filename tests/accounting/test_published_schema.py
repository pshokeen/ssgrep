@pytest.mark.parametrize("kind,raw", attacks())
def test_closed_schema_rejects_private_or_ambiguous_original_before_any_blob_write(
    kind, raw, tmp_path, monkeypatch
):
    # Observe the actual persistent sink, not mock-forwarding arguments. A valid
    # original creates a real envelope in the positive controls above.
    before = fingerprint(tmp_path / "data")
    writes = []
    real = store.write_blob

    def observed(*args, **kwargs):
        writes.append(True)
        return real(*args, **kwargs)

    monkeypatch.setattr(store, "write_blob", observed)
    with pytest.raises(ValueError):
        decode_original(raw, kind)
    with pytest.raises(CollectError) as failed:
        _envelope(PROFILE, raw, kind, 3, "2026-10-14T12:00:00Z")
    assert failed.value.condition == "migration_history_unavailable"
    assert writes == [] and fingerprint(tmp_path / "data") == before


def test_optional_original_reuse_shape_and_unavailable_quantity_are_supported():
    original = receipt()
    original["reuse"] = {
        "class": "none_observed",
        "relay": False,
        "report": False,
        "action_ok": False,
        "novel": False,
        "user_supplied": False,
    }
    original["costs"][0][1] = {
        "value": None,
        "unit": "work_seconds",
        "basis": "unavailable",
        "method": "",
        "reason": "lookup_work_seconds_not_modeled",
    }
    original["missing_costs"] = [["exposure:lookup", "lookup_work_seconds_not_modeled"]]
    assert decode_original(encoded(original), "receipt") == original
